// redirectsFile is the nginx include with one exact-match location per
// redirect. Include it in the server block of the site.
const redirectsFile = "_redirects.nginx"

func (g *generator) writeRedirects() error {
	for _, r := range g.snap.routes {
		if r.Kind != "redirect" {
			continue
		}
		var to string
		var ok bool
		switch {
		case r.ContentID != nil:
			var it *item
			if it, ok = g.itemByID[*r.ContentID]; ok {
				to = it.path
			}
		case r.CategoryID != nil:
			to, ok = g.catPath[*r.CategoryID]
		case r.TagID != nil:
			to, ok = g.tagPath[*r.TagID]
		}
		if !ok || to == r.Path {
			continue // target not public (yet); the old URL stays a 404
		}
		rel, safe := fileForPath(r.Path)
		if !safe || !nginxSafe(r.Path) {
			g.warn("redirect %q: unsafe path; skipped", r.Path)
			continue
		}
		page, err := redirectPage(absURL(g.opts.BaseURL, to), escapePath(to))
		if err != nil {
			return err
		}
		if err := g.out.write(rel, "redirect "+r.Path, page); err != nil {
			g.warn("%v; skipped", err)
			continue
		}
		g.redirects = append(g.redirects, redirect{from: r.Path, to: to})
	}

	var b strings.Builder
	b.WriteString("# Generated by Pagewright. Do not edit.\n")
	slices.SortFunc(g.redirects, func(a, b redirect) int { return strings.Compare(a.from, b.from) })
	for _, r := range g.redirects {
		// nginx matches location against the decoded URI, so the source is
		// the decoded path, quoted. The target is sent as a Location header,
		// so it is percent-encoded; $ is encoded too because return expands
		// variables.
		fmt.Fprintf(&b, "location = %s { return 301 %s; }\n",
			nginxQuote(r.from), nginxQuote(strings.ReplaceAll(escapePath(r.to), "$", "%24")))
	}
	return g.out.write(redirectsFile, systemOwner, []byte(b.String()))
}

// nginxSafe refuses characters that have no business in a path and could
// break out of a config line even when quoted.
func nginxSafe(p string) bool {
	return !strings.ContainsFunc(p, func(r rune) bool { return r < 0x20 || r == 0x7f })
}

// nginxQuote quotes s as an nginx config string.
func nginxQuote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

var redirectTmpl = template.Must(template.New("redirect").Parse(`<!doctype html>
<html lang="ja">
<head>
<meta charset="utf-8">
<meta name="robots" content="noindex">
<title>ページが移動しました</title>
<link rel="canonical" href="{{.Abs}}">
<meta http-equiv="refresh" content="{{.Refresh}}">
</head>
<body>
<p>このページは移動しました。<a href="{{.To}}">新しいページへ移動</a>してください。</p>
</body>
</html>
`))

// redirectPage is a tiny page that sends browsers on, for static servers
// that do not read the nginx include. to must already be percent-encoded.
func redirectPage(abs, to string) ([]byte, error) {
	var b bytes.Buffer
	err := redirectTmpl.Execute(&b, map[string]string{"Abs": abs, "To": to, "Refresh": "0; url=" + to})
	return b.Bytes(), err
}

func (g *generator) writeSitemap() error {
	type url struct {
		Loc     string `xml:"loc"`
		Lastmod string `xml:"lastmod,omitempty"`
	}
	type urlset struct {
		XMLName xml.Name `xml:"urlset"`
		Xmlns   string   `xml:"xmlns,attr"`
		URLs    []url    `xml:"url"`
	}
	slices.SortFunc(g.sitemap, func(a, b sitemapURL) int { return strings.Compare(a.path, b.path) })
	set := urlset{Xmlns: "http://www.sitemaps.org/schemas/sitemap/0.9"}
	for _, s := range g.sitemap {
		u := url{Loc: absURL(g.opts.BaseURL, s.path)}
		if !s.lastmod.IsZero() {
			u.Lastmod = s.lastmod.UTC().Format(time.RFC3339)
		}
		set.URLs = append(set.URLs, u)
	}
	return g.writeXML("sitemap.xml", set)
}

func (g *generator) writeFeed() error {
	type guid struct {
		Value       string `xml:",chardata"`
		IsPermaLink string `xml:"isPermaLink,attr"`
	}
	type rssItem struct {
		Title       string   `xml:"title"`
		Link        string   `xml:"link"`
		GUID        guid     `xml:"guid"`
		PubDate     string   `xml:"pubDate"`
		Description string   `xml:"description,omitempty"`
		Categories  []string `xml:"category"`
	}
	type atomLink struct {
		Href string `xml:"href,attr"`
		Rel  string `xml:"rel,attr"`
		Type string `xml:"type,attr"`
	}
	type channel struct {
		Title         string    `xml:"title"`
		Link          string    `xml:"link"`
		Description   string    `xml:"description"`
		Language      string    `xml:"language"`
		AtomLink      atomLink  `xml:"atom:link"`
		LastBuildDate string    `xml:"lastBuildDate,omitempty"`
		Items         []rssItem `xml:"item"`
	}
	type rss struct {
		XMLName xml.Name `xml:"rss"`
		Version string   `xml:"version,attr"`
		Atom    string   `xml:"xmlns:atom,attr"`
		Channel channel  `xml:"channel"`
	}
	base := g.opts.BaseURL
	ch := channel{
		Title:       g.site.Name,
		Link:        absURL(base, "/"),
		Description: g.site.Name + "のお知らせ",
		Language:    "ja",
		AtomLink:    atomLink{Href: absURL(base, g.site.FeedURL), Rel: "self", Type: "application/rss+xml"},
	}
	posts := g.posts()
	for _, it := range posts[:min(feedPosts, len(posts))] {
		link := absURL(base, it.path)
		ri := rssItem{
			Title:       title(it),
			Link:        link,
			GUID:        guid{Value: link, IsPermaLink: "true"},
			PubDate:     it.row.PublishedAt.UTC().Format(time.RFC1123Z),
			Description: excerpt(it.body.Text, 200),
		}
		for _, c := range it.cats {
			ri.Categories = append(ri.Categories, c.Title)
		}
		ch.Items = append(ch.Items, ri)
	}
	if len(posts) > 0 {
		// The newest post date, not the wall clock, so an unchanged site
		// produces an identical feed.
		ch.LastBuildDate = posts[0].row.PublishedAt.UTC().Format(time.RFC1123Z)
	}
	return g.writeXML("feed.xml", rss{Version: "2.0", Atom: "http://www.w3.org/2005/Atom", Channel: ch})
}

func (g *generator) writeXML(rel string, v any) error {
	var b bytes.Buffer
	b.WriteString(xml.Header)
	enc := xml.NewEncoder(&b)
	enc.Indent("", "  ")
	if err := enc.Encode(v); err != nil {
		return fmt.Errorf("encode %s: %w", rel, err)
	}
	b.WriteString("\n")
	return g.out.write(rel, systemOwner, b.Bytes())
}
